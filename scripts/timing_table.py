"""Build the README timing table from real run.json files (spec §10.4/§13). Never hand-edit the numbers.

    python scripts/timing_table.py examples/outputs/*/run.json > docs/timing_table.md
"""
import json
import sys
from pathlib import Path

STAGES = ["s1_input", "s2_understand", "s3_generate", "s4_prepare", "s5_reconstruct", "s6_cleanup", "s7_export", "s8_verify"]


def main(paths):
    rows = []
    for p in paths:
        r = json.loads(Path(p).read_text())
        if "error" in r:
            continue
        st = r.get("stages", {})
        gpu = (r.get("environment", {}).get("gpu") or {}).get("name", "?")
        rows.append([gpu, r.get("profile"), r["request"]["quality"], r.get("backend"), r.get("gen_profile"),
                     f"{st.get('s2_understand', {}).get('seconds', 0):.1f}", f"{st.get('s3_generate', {}).get('seconds', 0):.1f}",
                     f"{st.get('s5_reconstruct', {}).get('seconds', 0):.1f}",
                     f"{sum(st.get(s, {}).get('seconds', 0) for s in ('s4_prepare', 's6_cleanup', 's7_export', 's8_verify')):.1f}",
                     f"{r.get('total_seconds', 0):.1f}", f"{max((v.get('vram_peak_gb', 0) for v in st.values()), default=0):.1f}",
                     f"{(r.get('backend_meta') or {}).get('vram_peak_gb', 0):.1f}",
                     f"{r.get('sketch_fidelity', 0):.2f}", Path(p).parent.name])
    hdr = ["GPU", "profile", "preset", "3D backend", "2D gen", "S2 s", "S3 (2D) s", "S5 (3D) s", "S4+S6–S8 s", "total s",
           "2D peak VRAM GB", "3D peak VRAM GB", "sketch match", "run"]
    print("| " + " | ".join(hdr) + " |\n|" + "---|" * len(hdr))
    for r in rows:
        print("| " + " | ".join(str(x) for x in r) + " |")
    print(f"\n_Generated by `scripts/timing_table.py` from {len(rows)} run.json file(s). 3D VRAM is measured inside the backend"
          " subprocess (nvidia-smi polling); 2D VRAM is torch.cuda.max_memory_allocated in the parent._")


if __name__ == "__main__":
    main(sys.argv[1:])
